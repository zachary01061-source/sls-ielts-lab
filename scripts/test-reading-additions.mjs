import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {mergeReadingCatalog,passageRequestUrl,readingSearchText,withoutRepeatedQuestionPrefix} from '../public/reading-catalog.mjs';
import {configurePractice,recentEntriesFor,matchesGroupFilters} from '../public/practice-levels.mjs';
import {questionsOf,grade} from '../public/core.mjs';
import {questionsOf as questionsOfBrowser} from '../public/core.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const json=file=>JSON.parse(fs.readFileSync(path.join(root,file),'utf8'));
const original=json('public/data/index.json'),before=JSON.stringify(original);
const supplement=json('public/data/reading-additions/index.json');
const merged=mergeReadingCatalog(original,supplement);
assert.equal(original.passages.length,355,'The original catalog remains its preserved 355-entry snapshot.');
assert.equal(merged.length,356,'A supplemental passage extends the practice catalog.');
assert.equal(JSON.stringify(original),before,'Merging must not alter the source snapshot.');
const additions=merged.filter(p=>p.supplementary);
assert.equal(additions.length,1);
const meta=additions[0],paper=json('public/'+meta.file);
assert.equal(meta.id,paper.id);
assert.equal(paper.preserveSourceNumbers,true);
assert.equal(paper.groups.reduce((n,g)=>n+g.questions.length,0),14);
assert.match(passageRequestUrl(meta),/reading-additions\/passages\/[^?]+\.json\?v=20261118-money$/);
assert.equal(passageRequestUrl(merged[0]),'./'+merged[0].file,'Original asset URLs remain unchanged.');
const collision=mergeReadingCatalog(original,{passages:[{...meta,id:original.passages[0].id,title:'must not replace original'}]});
assert.equal(collision.length,355);assert.equal(collision[0].title,original.passages[0].title);
const rows=questionsOf([paper]);
assert.deepEqual(rows.map(q=>q.displayNumber),Array.from({length:14},(_,i)=>i+27),'The single-passage answer UI keeps original question numbers27–40.');
assert.deepEqual(rows.map(q=>q.number),Array.from({length:14},(_,i)=>i+1),'Internal navigation ordinals remain unique and consecutive.');
assert.deepEqual(questionsOfBrowser([paper]).map(q=>q.displayNumber),rows.map(q=>q.displayNumber),'Browser and server/shared core numbering agree.');
const q27=rows[0].question,q29=rows.find(x=>x.question.sourceSlot===29).question,q31=rows.find(x=>x.question.sourceSlot===31).question;
assert.ok(!/^\s*\*\*27\*\*/.test(withoutRepeatedQuestionPrefix(q27.prompt,q27,paper)),'The question badge is the only leading number.');
assert.ok(withoutRepeatedQuestionPrefix(q31.prompt,q31,paper).includes('**31**'),'Summary answer-slot numbers inside the sentence remain visible.');
assert.equal(withoutRepeatedQuestionPrefix(q27.prompt,q27,{...paper,preserveSourceNumbers:false}),q27.prompt,'Existing passage prompt rendering stays unchanged.');
assert.equal(q29.answers[0],'C');assert.equal(q29.sourceAnswer,'D');
assert.match(q29.explanation,/来源答案标D/);assert.match(q29.explanation,/校正为C/);
const appSource=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
assert.ok(appSource.includes('const explain=q.explanation')&&appSource.includes('${rich(explain)}'),'Answer review renders the correction explanation separately from the original evidence quote.');
const answers=Object.fromEntries(rows.map(x=>[x.key,x.question.answers[0]]));
assert.equal(grade([paper],answers).correct,14,'All14 verified answers can be submitted and scored.');
const restored=JSON.parse(JSON.stringify({passages:[paper],answers}));
assert.equal(grade(restored.passages,restored.answers).correct,14,'Saved/resumed snapshots retain answer keys and scoring.');
assert.deepEqual(questionsOf(restored.passages).map(q=>q.displayNumber),rows.map(q=>q.displayNumber));
for(const oldMeta of original.passages){const old=json('public/'+oldMeta.file);assert.deepEqual(questionsOf([old]).map(x=>x.displayNumber),Array.from({length:old.groups.reduce((n,g)=>n+g.questions.length,0)},(_,i)=>i+1),'Existing reading practice keeps its original numbering behavior.');}
const enrichment=json('public/practice-enrichment.json');configurePractice(enrichment);
const recent=recentEntriesFor('reading',merged);
assert.equal(recent.length,37);assert.equal(recent.filter(p=>!p.external).length,35);assert.equal(recent.filter(p=>p.external).length,2);
const matched=recent.find(p=>p.id===meta.id);assert.ok(matched&&!matched.external,'The recent money article now resolves to the local passage.');
assert.match(readingSearchText(matched),/did it really originate from bartering/i);
assert.match(readingSearchText(matched),/controversy about the origins of money/i,'Both uploaded title and source catalog alias are searchable.');
assert.equal(matchesGroupFilters(matched,{type:'单选题',level:'medium'}),true);
assert.equal(matchesGroupFilters(matched,{type:'单选题',level:'easy'}),false);
console.log('Reading additions passed:356 entries;35/37 recent local; original Q27–40;14/14 scoring and resume; all355 original numbering behaviors preserved.');
